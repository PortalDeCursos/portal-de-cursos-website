const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');

(async () => {
  const navegador = await chromium.launch({ channel: 'msedge', headless: true });
  const pagina = await navegador.newPage({ viewport: { width: 1440, height: 1000 }, colorScheme: 'light' });
  const erros = [];
  pagina.on('pageerror', erro => erros.push(erro.message));
  await pagina.route('**/dados/cursos.json', async rota => {
    await new Promise(resolver => setTimeout(resolver, 900));
    await rota.continue();
  });
  await pagina.goto('http://127.0.0.1:5173/#cursos');
  await pagina.getByRole('status', { name: 'Carregando cursos' }).waitFor();
  await pagina.screenshot({ path: 'verificacoes/cursos-carregando.png', fullPage: true });
  await pagina.getByRole('heading', { name: 'Análise e Desenvolvimento de Sistemas (TADS)', exact: true }).waitFor();
  await pagina.evaluate(() => document.fonts.ready);
  const lateral = await pagina.getByRole('complementary', { name: 'Filtros de cursos' }).boundingBox();
  const resultados = await pagina.locator('.pagina-cursos__resultados').boundingBox();
  assert(lateral.x + lateral.width < resultados.x, 'Os filtros devem ficar à esquerda dos resultados.');
  await pagina.screenshot({ path: 'verificacoes/cursos-claro.png', fullPage: true });
  const busca = pagina.getByRole('searchbox', { name: 'Buscar por nome ou sigla do curso' });
  await busca.fill('analise');
  assert.equal(await pagina.locator('.grade-catalogo > article').count(), 1);
  await busca.fill('Inteligência Artificial Quântica');
  await pagina.getByRole('heading', { name: 'Nenhum curso encontrado' }).waitFor();
  await pagina.screenshot({ path: 'verificacoes/cursos-vazio.png', fullPage: true });
  await pagina.getByRole('button', { name: 'Limpar filtros', exact: true }).last().click();
  assert.equal(await pagina.locator('.grade-catalogo > article').count(), 2);
  await pagina.getByRole('checkbox', { name: 'Noturno' }).check();
  assert.equal(await pagina.locator('.grade-catalogo > article').count(), 1);
  await pagina.getByRole('link', { name: 'Conhecer o curso', exact: true }).click();
  await pagina.getByRole('heading', {name:'Análise e Desenvolvimento de Sistemas (TADS)',exact:true}).waitFor();
  await pagina.getByRole('navigation',{name:'Navegação principal'}).getByRole('link',{name:'Cursos',exact:true}).click();
  await pagina.getByRole('heading',{name:'Conheça nossos cursos'}).waitFor();
  assert(pagina.url().endsWith('#cursos'));
  await pagina.unroute('**/dados/cursos.json');
  await pagina.route('**/dados/cursos.json', rota => rota.fulfill({ status: 503, body: 'Indisponível' }));
  await pagina.reload();
  await pagina.getByRole('heading', { name: 'Não foi possível carregar os cursos' }).waitFor();
  assert(await pagina.getByRole('checkbox', { name: 'Noturno' }).isChecked());
  assert(await pagina.getByRole('checkbox', { name: 'Noturno' }).isDisabled());
  await pagina.evaluate(() => { document.activeElement?.blur(); window.scrollTo({top:0,behavior:'instant'}) });
  await pagina.screenshot({ path: 'verificacoes/cursos-erro.png', fullPage: true });
  await pagina.unroute('**/dados/cursos.json');
  await pagina.getByRole('button', { name: 'Tentar novamente' }).click();
  await pagina.getByRole('heading', { name: 'Análise e Desenvolvimento de Sistemas (TADS)', exact: true }).waitFor();
  await pagina.getByRole('button', { name: 'Limpar filtros', exact: true }).click();
  await pagina.getByRole('button', { name: 'Ativar modo escuro' }).click();
  assert.equal(await pagina.evaluate(() => getComputedStyle(document.documentElement).backgroundColor), 'rgb(0, 0, 0)');
  await pagina.screenshot({ path: 'verificacoes/cursos-amoled.png', fullPage: true });
  await pagina.setViewportSize({ width: 390, height: 844 });
  await pagina.getByRole('button', { name: 'Filtrar cursos', exact: true }).click();
  await pagina.screenshot({ path: 'verificacoes/cursos-celular.png', fullPage: true });
  assert.equal(await pagina.evaluate(() => document.documentElement.scrollWidth), 390);
  assert.equal(await pagina.evaluate(() => [...document.images].filter(imagem => !imagem.complete || !imagem.naturalWidth).length), 0);
  await pagina.getByRole('checkbox', { name: 'Matutino' }).check();
  await pagina.getByRole('button', { name: 'Recolher filtros' }).click();
  assert.equal(await pagina.locator('.grade-catalogo > article').count(), 1);
  assert.deepEqual(erros, []);
  fs.writeFileSync('verificacoes/catalogo-resultados.json', JSON.stringify({ filtrosEsquerda: true, buscaSemAcento: true, vazio: true, carregamento: true, erro503: true, recuperacao: true, filtrosPreservados: true, detalhes: true, amoled: true, celular390: true, imagensQuebradas: 0, erros }, null, 2));
  console.log('Catálogo: todos os cenários passaram.');
  await navegador.close();
})().catch(erro => { console.error(erro); process.exitCode = 1; });
